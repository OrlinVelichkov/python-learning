# Даден е списък с двойки [("Ана", 5.50), ("Боян", 4.75), ("Вера", 6.00)]. Намери името с най-висока оценка и средния успех, закръглен до втория знак — без цикъл for.
grades = [("Ана", 5.50), ("Боян", 4.75), ("Вера", 6.00)]

best = max(grades, key=lambda pair: pair[1])[0]
print(best)  
avg = round(sum(g for _, g in grades) / len(grades), 2)

print(best, avg)      # Вера 5.42